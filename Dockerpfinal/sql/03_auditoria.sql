-- 03_auditoria.sql  (se ejecuta como postgres)
-- Bitacora de auditoria, trigger de control de cambios y proteccion de la bitacora.

-- 1. Bitacora en su propio tablespace
CREATE TABLE rrhh.audit_log_empleados (
    audit_id         BIGINT GENERATED BY DEFAULT AS IDENTITY
                         PRIMARY KEY USING INDEX TABLESPACE ts_rrhh_audit,
    accion           VARCHAR(10)  NOT NULL,
    emp_id           INTEGER,
    usuario_bd       NAME         NOT NULL,
    fecha_operacion  TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),
    salario_anterior NUMERIC(10,2),
    salario_nuevo    NUMERIC(10,2),
    ip_origen        INET
) TABLESPACE ts_rrhh_audit;

-- 2. Trigger de auditoria (SECURITY DEFINER: registra aunque el usuario no tenga
--    privilegios sobre la bitacora). Los cambios de salario tambien alimentan el historial.
CREATE FUNCTION rrhh.fn_audit_empleados() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = rrhh, pg_temp AS
$$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO audit_log_empleados (accion, emp_id, usuario_bd, salario_nuevo, ip_origen)
        VALUES ('INSERT', NEW.emp_id, session_user, NEW.salario, inet_client_addr());
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO audit_log_empleados (accion, emp_id, usuario_bd, salario_anterior, salario_nuevo, ip_origen)
        VALUES ('UPDATE', NEW.emp_id, session_user, OLD.salario, NEW.salario, inet_client_addr());
        IF NEW.salario <> OLD.salario THEN
            INSERT INTO historial_salarios (emp_id, fecha_ingreso, salario, motivo)
            VALUES (NEW.emp_id, NEW.fecha_ingreso, NEW.salario, 'Cambio de salario registrado por trigger');
        END IF;
        RETURN NEW;
    ELSE
        INSERT INTO audit_log_empleados (accion, emp_id, usuario_bd, salario_anterior, ip_origen)
        VALUES ('DELETE', OLD.emp_id, session_user, OLD.salario, inet_client_addr());
        RETURN OLD;
    END IF;
END;
$$;

CREATE TRIGGER trg_audit_empleados
AFTER INSERT OR UPDATE OR DELETE ON rrhh.empleados
FOR EACH ROW EXECUTE FUNCTION rrhh.fn_audit_empleados();
--;;
-- 3. Bitacora inmutable: ni siquiera el administrador puede modificarla o vaciarla
CREATE FUNCTION rrhh.fn_bitacora_inmutable() RETURNS trigger
LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION 'La bitacora de auditoria es inmutable (% bloqueado)', TG_OP;
END;
$$;

CREATE TRIGGER trg_bitacora_inmutable
BEFORE UPDATE OR DELETE ON rrhh.audit_log_empleados
FOR EACH ROW EXECUTE FUNCTION rrhh.fn_bitacora_inmutable();

CREATE TRIGGER trg_bitacora_no_truncate
BEFORE TRUNCATE ON rrhh.audit_log_empleados
FOR EACH STATEMENT EXECUTE FUNCTION rrhh.fn_bitacora_inmutable();

SELECT tgname AS trigger, tgrelid::regclass AS tabla,
       CASE WHEN tgenabled = 'O' THEN 'ACTIVO' ELSE tgenabled::text END AS estado
FROM pg_trigger
WHERE NOT tgisinternal AND tgrelid::regclass::text LIKE 'rrhh.%'
ORDER BY tgrelid::regclass::text, tgname;
