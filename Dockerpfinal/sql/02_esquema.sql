-- 02_esquema.sql  (se ejecuta como usr_admin)
-- Esquema relacional: roles, departamentos, empleados (particionada por rango) e historial.

-- 1. Catalogos
CREATE TABLE rrhh.roles (
    rol_id       SMALLINT PRIMARY KEY USING INDEX TABLESPACE ts_rrhh_idx,
    nombre_rol   VARCHAR(50) NOT NULL UNIQUE USING INDEX TABLESPACE ts_rrhh_idx,
    nivel_acceso VARCHAR(20) NOT NULL DEFAULT 'CONFIDENCIAL',
    descripcion  VARCHAR(200)
) TABLESPACE ts_rrhh_data;

CREATE TABLE rrhh.departamentos (
    depto_id                SMALLINT PRIMARY KEY USING INDEX TABLESPACE ts_rrhh_idx,
    nombre_depto            VARCHAR(60) NOT NULL UNIQUE USING INDEX TABLESPACE ts_rrhh_idx,
    presupuesto_anual       NUMERIC(14,2) CHECK (presupuesto_anual >= 0),
    clasificacion_seguridad VARCHAR(20) DEFAULT 'RESTRINGIDO'
) TABLESPACE ts_rrhh_data;
--;;
-- 2. Tabla de empleados particionada por rango de fecha de ingreso
--    clasificacion_nivel se usa para MAC (1 Publico, 2 Confidencial, 3 Secreto)
CREATE TABLE rrhh.empleados (
    emp_id              INTEGER       NOT NULL,
    nombre              VARCHAR(50)   NOT NULL,
    apellido            VARCHAR(50)   NOT NULL,
    email               VARCHAR(100),
    salario             NUMERIC(10,2) NOT NULL CHECK (salario > 0),
    fecha_ingreso       DATE          NOT NULL,
    depto_id            SMALLINT      NOT NULL REFERENCES rrhh.departamentos (depto_id),
    rol_id              SMALLINT      NOT NULL REFERENCES rrhh.roles (rol_id),
    clasificacion_nivel SMALLINT      NOT NULL DEFAULT 1 CHECK (clasificacion_nivel BETWEEN 1 AND 3),
    CONSTRAINT pk_empleados PRIMARY KEY (emp_id, fecha_ingreso)
        USING INDEX TABLESPACE ts_rrhh_idx
) PARTITION BY RANGE (fecha_ingreso);

CREATE TABLE rrhh.p_historico  PARTITION OF rrhh.empleados
    FOR VALUES FROM (MINVALUE)     TO ('2021-01-01') TABLESPACE ts_rrhh_part;
CREATE TABLE rrhh.p_2021_2022  PARTITION OF rrhh.empleados
    FOR VALUES FROM ('2021-01-01') TO ('2023-01-01') TABLESPACE ts_rrhh_part;
CREATE TABLE rrhh.p_2023_2024  PARTITION OF rrhh.empleados
    FOR VALUES FROM ('2023-01-01') TO ('2025-01-01') TABLESPACE ts_rrhh_part;
CREATE TABLE rrhh.p_2025_2026  PARTITION OF rrhh.empleados
    FOR VALUES FROM ('2025-01-01') TO ('2027-01-01') TABLESPACE ts_rrhh_part;
CREATE TABLE rrhh.p_futuro     PARTITION OF rrhh.empleados
    FOR VALUES FROM ('2027-01-01') TO (MAXVALUE)     TABLESPACE ts_rrhh_part;
--;;
-- 3. Historial de salarios (referencia a la llave compuesta de empleados)
CREATE TABLE rrhh.historial_salarios (
    hist_id        INTEGER GENERATED BY DEFAULT AS IDENTITY
                       PRIMARY KEY USING INDEX TABLESPACE ts_rrhh_idx,
    emp_id         INTEGER NOT NULL,
    fecha_ingreso  DATE    NOT NULL,
    salario        NUMERIC(10,2) NOT NULL,
    vigente_desde  DATE    NOT NULL DEFAULT CURRENT_DATE,
    motivo         VARCHAR(100),
    FOREIGN KEY (emp_id, fecha_ingreso) REFERENCES rrhh.empleados (emp_id, fecha_ingreso)
) TABLESPACE ts_rrhh_data;
--;;
-- 4. Ubicacion fisica de cada objeto (tabla / particion / indice -> tablespace)
SELECT c.relname AS objeto, c.relkind AS tipo,
       COALESCE(t.spcname, 'pg_default') AS tablespace
FROM pg_class c
LEFT JOIN pg_tablespace t ON t.oid = c.reltablespace
WHERE c.relnamespace = 'rrhh'::regnamespace AND c.relkind IN ('r', 'p', 'i', 'I')
ORDER BY c.relkind, c.relname;
--;;
-- 5. Nivel de autorizacion (MAC) de cada usuario y funcion que lo consulta
CREATE TABLE rrhh.autorizaciones (
    usuario NAME PRIMARY KEY,
    nivel   SMALLINT NOT NULL CHECK (nivel BETWEEN 1 AND 3)
) TABLESPACE ts_rrhh_data;

CREATE FUNCTION rrhh.nivel_usuario() RETURNS SMALLINT
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = rrhh, pg_temp AS
$$ SELECT COALESCE((SELECT nivel FROM rrhh.autorizaciones WHERE usuario = session_user), 0) $$;

-- 6. Vista de negocio: oculta lo que excede la autorizacion MAC del usuario.
--    security_barrier obliga a aplicar primero el filtro MAC: sin ella, un filtro del
--    usuario (p. ej. una division entre cero o un cast) se evaluaria antes y sus
--    mensajes de error revelarian datos de filas ocultas.
CREATE VIEW rrhh.v_resumen_empleados WITH (security_barrier = true) AS
SELECT e.emp_id,
       e.nombre || ' ' || e.apellido AS nombre_completo,
       e.email,
       d.nombre_depto,
       r.nombre_rol,
       e.fecha_ingreso,
       e.salario,
       e.clasificacion_nivel
FROM rrhh.empleados e
JOIN rrhh.departamentos d ON e.depto_id = d.depto_id
JOIN rrhh.roles r         ON e.rol_id   = r.rol_id
WHERE e.clasificacion_nivel <= rrhh.nivel_usuario();
